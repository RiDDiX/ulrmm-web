<script setup lang="ts">
import { ref, computed, onMounted } from "vue";
import { useQuasar } from "quasar";
import { useStore } from "vuex";
import {
  fetchRustDeskSettings,
  saveRustDeskSettings,
  fetchRustDeskReleases,
  checkRustDeskReleases,
  updateRustDeskServer,
  pinRustDeskClient,
  updateRustDeskClients,
} from "@/api/rustdesk";
import { withStepUp } from "@/components/vault/stepUp";
import { copyOutput } from "@/utils/helpers";
import { notifySuccess } from "@/utils/notify";
import SettingsPanelHeader from "@/components/modals/coresettings/SettingsPanelHeader.vue";

interface RustDeskSettings {
  enabled: boolean;
  id_server: string;
  relay_server: string;
  public_key: string;
  key_present: boolean;
  config_string: string;
  server_version: string;
  auto_update_server: boolean;
  auto_update_clients: boolean;
}

interface ReleaseInfo {
  version: string;
  published_at: string | null;
  url: string;
  notes: string;
}

interface Releases {
  server: {
    installed: string;
    latest: ReleaseInfo | null;
    update_available: boolean;
    arch_supported: boolean;
  };
  client: {
    pinned: string;
    latest: ReleaseInfo | null;
    update_available: boolean;
    mirrored_at: string | null;
    outdated_peers: number;
    online_outdated_peers: number;
  };
  releases_checked_at: string | null;
}

const settings = ref<RustDeskSettings | null>(null);
const loading = ref(false);
const saving = ref(false);

const $q = useQuasar();
const store = useStore();
const formatDate = computed(() => store.getters.formatDate);

const releases = ref<Releases | null>(null);
const relLoading = ref(false);
const relError = ref("");
const checking = ref(false);
const updatingServer = ref(false);
const pinning = ref(false);
const updatingClients = ref(false);
const queued = ref<number | null>(null);
const busy = computed(
  () =>
    checking.value ||
    updatingServer.value ||
    pinning.value ||
    updatingClients.value,
);

const outdatedText = computed(() => {
  const c = releases.value?.client;
  if (!c?.outdated_peers) return "no outdated clients";
  return `${c.outdated_peers} outdated (${c.online_outdated_peers} online)`;
});

// bulk update goes to online devices
const updateClientsLabel = computed(() => {
  const n = releases.value?.client.online_outdated_peers ?? 0;
  return `Update ${n} online client${n === 1 ? "" : "s"}`;
});

interface HttpError {
  response?: { status: number; data?: unknown };
}

// notify_error body is a string; DRF sends detail or field errors
function errText(err: unknown): string {
  const e = err as HttpError;
  const data = e?.response?.data;
  if (typeof data === "string" && !data.trimStart().startsWith("<")) {
    return data;
  }
  if (data && typeof data === "object") {
    const d = data as Record<string, unknown>;
    const first = d.detail ?? Object.values(d)[0];
    if (first) return String(Array.isArray(first) ? first[0] : first);
  }
  return e?.response
    ? `The server returned an error (${e.response.status}).`
    : "The server could not be reached.";
}

async function loadReleases() {
  relLoading.value = true;
  relError.value = "";
  try {
    releases.value = await fetchRustDeskReleases({ silent: true });
  } catch (e) {
    console.error(e);
    relError.value = errText(e);
  } finally {
    relLoading.value = false;
  }
}

// one release call; failure shown in the banner, not a toast
async function runRelease<T>(
  flag: { value: boolean },
  call: () => Promise<T>,
): Promise<T | null> {
  flag.value = true;
  relError.value = "";
  queued.value = null;
  try {
    return await call();
  } catch (e) {
    console.error(e);
    relError.value = errText(e);
    return null;
  } finally {
    flag.value = false;
  }
}

async function checkNow() {
  const data = await runRelease<Releases>(checking, () =>
    checkRustDeskReleases({ silent: true }),
  );
  if (data) releases.value = data;
}

async function updateServer() {
  const version = releases.value?.server.latest?.version;
  if (!version) return;
  const data = await runRelease<Releases | null>(updatingServer, async () => {
    // hand withStepUp the first step-up 403; it toasts other errors,
    // so keep those and throw them once it returns
    let asked = false;
    let failure: unknown = null;
    const res = await withStepUp($q, (config: object) =>
      updateRustDeskServer(version, config).catch((e: HttpError) => {
        const body = e?.response?.data as { stepup?: boolean } | undefined;
        if (e?.response?.status === 403 && body?.stepup && !asked) {
          asked = true;
          throw e;
        }
        failure = e;
        return null;
      }),
    );
    if (failure) throw failure;
    return res;
  });
  if (!data) return;
  releases.value = data;
  if (settings.value) settings.value.server_version = data.server.installed;
  notifySuccess(`RustDesk server updated to ${version}`);
}

async function pinLatest() {
  const version = releases.value?.client.latest?.version;
  if (!version) return;
  const data = await runRelease<Releases>(pinning, () =>
    pinRustDeskClient(version, { silent: true }),
  );
  if (!data) return;
  releases.value = data;
  notifySuccess(`Clients are pinned to ${version}`);
}

async function updateClients() {
  const data = await runRelease<{ queued: number }>(updatingClients, () =>
    updateRustDeskClients({ silent: true }),
  );
  if (data) queued.value = data.queued;
}

async function load() {
  loading.value = true;
  try {
    settings.value = await fetchRustDeskSettings();
  } catch (e) {
    console.error(e);
    settings.value = null;
  } finally {
    loading.value = false;
  }
}

async function save() {
  if (!settings.value) return;
  saving.value = true;
  try {
    settings.value = await saveRustDeskSettings({
      enabled: settings.value.enabled,
      id_server: settings.value.id_server.trim(),
      relay_server: settings.value.relay_server.trim(),
      auto_update_server: settings.value.auto_update_server,
      auto_update_clients: settings.value.auto_update_clients,
    });
    notifySuccess("RustDesk settings were saved");
  } catch (e) {
    console.error(e);
  } finally {
    saving.value = false;
  }
}

onMounted(() => {
  load();
  loadReleases();
});
</script>

